create table if not exists public.homepage_sections (
  id bigint generated by default as identity primary key,
  section_type text not null unique check (
    section_type in (
      'hero',
      'service_times',
      'featured_sermon',
      'visit_cards',
      'giving_cta',
      'announcements'
    )
  ),
  title text,
  is_active boolean not null default true,
  display_order integer not null default 0
);

alter table public.homepage_sections enable row level security;

grant select on table public.homepage_sections to anon;
grant select, update on table public.homepage_sections to authenticated;

drop policy if exists "public read homepage sections"
  on public.homepage_sections;
create policy "public read homepage sections"
  on public.homepage_sections
  for select
  to anon
  using (is_active = true);

drop policy if exists "authenticated read homepage sections"
  on public.homepage_sections;
create policy "authenticated read homepage sections"
  on public.homepage_sections
  for select
  to authenticated
  using (true);

drop policy if exists "authenticated update homepage sections"
  on public.homepage_sections;
create policy "authenticated update homepage sections"
  on public.homepage_sections
  for update
  to authenticated
  using (true)
  with check (true);

insert into public.homepage_sections (section_type, title, display_order)
values
  ('hero', 'Hero Banner', 0),
  ('service_times', 'Service Times', 1),
  ('featured_sermon', 'Latest Sermon', 2),
  ('visit_cards', 'Visit Information', 3),
  ('giving_cta', 'Giving Call to Action', 4),
  ('announcements', 'Announcements', 5)
on conflict (section_type) do nothing;
